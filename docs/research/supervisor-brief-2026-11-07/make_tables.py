#!/usr/bin/env python3
"""Generate macros.tex, numbers.tex and the table fragments of the 2026-11-07 brief.

* macros.tex           short macros such as \\RC{p50}{th_verbs}{1024} that expand to \\N{key}
* numbers.tex          one macro per \\N{key} used in the TeX sources (key grammar: see data.py)
* tab-*.tex            tabulars only; main.tex adds the table environment and caption
* appendix-tables.tex  all five value sizes
An unknown or ambiguous key raises an error, so the PDF cannot be built with a number that has no source.
"""
import re
from pathlib import Path

from data import SIZES, Data, build_stats, evaluate

HERE = Path(__file__).resolve().parent
data = Data()
stats = build_stats(data)
LIVE = ['native', 'th_tcp', 'th_verbs', 'th_kernel', 'th_spdk', 'valkey_tcp', 'valkey_rdma']
NAMES = {'native': 'Native', 'th_tcp': 'TH TCP', 'th_verbs': 'TH verbs', 'th_kernel': 'TH NVMe-oF kernel',
         'th_spdk': 'TH NVMe-oF SPDK', 'valkey_tcp': 'Valkey TCP', 'valkey_rdma': 'Valkey RDMA',
         'tikv': 'TiKV', 'cassandra': 'Cassandra', 'foundationdb': 'FoundationDB', 'kvrocks': 'Kvrocks',
         'garnet': 'Garnet'}
STAR = '$^{*}$'

# Each macro \XX{kind}{label}{size} stands for \N{kind:label:cohort:profile:op:size}.
MACROS = {
    'RC': 'primary_rf1:read-concurrent:read',
    'WC': 'primary_rf1:write-concurrent:put',
    'MR': 'primary_rf1:read-many32:get_many',
    'WB': 'primary_rf1:write-batch32:put_batch',
    'PR': 'primary_rf1:point-mixed:read',
    'PP': 'primary_rf1:point-mixed:put',
    'FT': 'sealed_read:first_touch-scalar-c1-baseline:read',
    'RR': 'sealed_read:repeat_read-scalar-c1-baseline:read',
    'FS': 'sealed_read:first_touch-scalar-c16-baseline:read',
    'CO': 'cold_os_cache:cold-os-large:read',
    'CC': 'coordinator_cache_configured:coordinator-cache:read',
}


def write_macros():
    lines = ['% Generated by make_tables.py. Do not edit.']
    for name, middle in MACROS.items():
        lines.append('\\newcommand{\\%s}[3]{\\N{#1:#2:%s:#3}}' % (name, middle))
    (HERE / 'macros.tex').write_text('\n'.join(lines) + '\n')


def write_numbers():
    keys = set()
    pattern = re.compile(r'\\(%s)\{([^{}]+)\}\{([^{}]+)\}\{([^{}]+)\}' % '|'.join(MACROS))
    for path in sorted(HERE.glob('*.tex')):
        if path.name in ('numbers.tex', 'macros.tex', 'appendix-tables.tex') or path.name.startswith('tab-'):
            continue
        text = path.read_text()
        keys.update(re.findall(r'\\N\{([^{}]+)\}', text))
        for name, kind, label, size in pattern.findall(text):
            keys.add(f'{kind}:{label}:{MACROS[name]}:{size}')
    lines = ['% Generated by make_tables.py from the keys used in the TeX sources. Do not edit.']
    for key in sorted(keys):
        value = evaluate(key, data, stats)
        lines.append('\\expandafter\\gdef\\csname n@\\detokenize{%s}\\endcsname{%s}' % (key, value))
    (HERE / 'numbers.tex').write_text('\n'.join(lines) + '\n')
    return len(keys)


# ---- cell helpers -----------------------------------------------------------------------------
def fmt(value):
    if value < 10:
        return f'{value:.2f}'
    if value < 100:
        return f'{value:.1f}'
    return f'{value:,.0f}'.replace(',', '{,}')


def cps(value):
    return f'{value:,.0f}'.replace(',', '{,}')


def cell(label, cohort, profile, op, size):
    row = data.maybe(label, cohort, profile, op, size)
    if not row:
        return '--'
    text = '/'.join([fmt(row['api_p50_us']), fmt(row['api_p99_us']), cps(row['case_success_calls_per_second'])])
    return text + (STAR if row['flag_spdk_accounting'] else '')


def write(name, lines):
    (HERE / name).write_text('\n'.join(lines) + '\n')


# ---- 1 KiB tables ------------------------------------------------------------------------------
def one_kib():
    def block(left, right, head_left, head_right, size=1024):
        out = [r'\small', r'\begin{tabular}{lrrr|rrr}\toprule',
               r'& \multicolumn{3}{c|}{' + head_left + r'} & \multicolumn{3}{c}{' + head_right + r'}\\',
               r'Backend & p50 & p99 & calls/s & p50 & p99 & calls/s\\\midrule']
        for label in LIVE:
            cells = []
            for profile, op in (left, right):
                row = data.maybe(label, 'primary_rf1', profile, op, size)
                if row is None:
                    cells += ['--', '--', '--']
                else:
                    star = STAR if row['flag_spdk_accounting'] else ''
                    cells += [fmt(row['api_p50_us']) + star, fmt(row['api_p99_us']),
                              cps(row['case_success_calls_per_second'])]
            out.append(NAMES[label] + ' & ' + ' & '.join(cells) + r'\\')
        return out + [r'\bottomrule\end{tabular}']
    write('tab-onekib-1.tex', block(('read-concurrent', 'read'), ('write-concurrent', 'put'), 'Scalar read',
                                    'Scalar write'))
    write('tab-onekib-2.tex', block(('read-many32', 'get_many'), ('write-batch32', 'put_batch'), 'Read-many32',
                                    'Write-batch32'))


# ---- NVMe tables -------------------------------------------------------------------------------------
def nvme_tables():
    profile = 'first_touch-scalar-c1-baseline'
    rows = []
    for size in SIZES:
        cells = [f'{size:,}'.replace(',', '{,}')]
        kernel = data.pop('th_kernel', 'sealed_read', profile, 'read', size)
        spdk = data.pop('th_spdk', 'sealed_read', profile, 'read', size)
        dk, ds = data.device_per_call(kernel), data.device_per_call(spdk)
        cells += [f"{dk['initb']:,.0f}".replace(',', '{,}'), f"{dk['initb'] / size:.1f}"]
        cells += [fmt(kernel['api_p50_us']), fmt(kernel['api_p99_us']), f"{dk['initus']:.1f}", f"{dk['dev']:.3f}"]
        cells += [fmt(spdk['api_p50_us']), fmt(spdk['api_p99_us']), f"{ds['initus']:.1f}", f"{ds['dev']:.3f}",
                  f"{ds['devus']:.1f}"]
        rows.append(' & '.join(cells) + r'\\')
    write('tab-nvme-cmd.tex', [r'\scriptsize', r'\resizebox{\linewidth}{!}{%', r'\begin{tabular}{rrr|rrrr|rrrrr}\toprule',
                               r'& \multicolumn{2}{c|}{Initiator} & \multicolumn{4}{c|}{Kernel target (buffered file)} & '
                               r'\multicolumn{5}{c}{SPDK target (O\_DIRECT file AIO)}\\',
                               r'Value B & B/call & $\times$ & p50 & p99 & cmd \us & dev/call & p50 & p99 & cmd \us & '
                               r'dev/call & dev \us\\\midrule'] + rows + [r'\bottomrule\end{tabular}}'])
    heads = ['Native', 'TH TCP', 'TH verbs', 'Kernel NVMe-oF', 'SPDK NVMe-oF']
    labels = ['native', 'th_tcp', 'th_verbs', 'th_kernel', 'th_spdk']
    out = [r'\small', r'\begin{tabular}{l|rrrrr|r|rr|r}\toprule',
           r'& \multicolumn{5}{c|}{First-touch c1, value bytes} & Repeat c1 & \multicolumn{2}{c|}{Live read c16} & Cold c16\\',
           r'Path & 64 & 256 & 1K & 8K & 64K & 64K & 1K & 64K & 64K\\\midrule']
    for head, label in zip(heads, labels):
        cells = []
        for size in SIZES:
            row = data.maybe(label, 'sealed_read', profile, 'read', size)
            cells.append(f"{data.device_per_call(row)['dev']:.3f}" if row else '--')
        for cohort, prof, size in (('sealed_read', 'repeat_read-scalar-c1-baseline', 65536),
                                   ('primary_rf1', 'read-concurrent', 1024), ('primary_rf1', 'read-concurrent', 65536),
                                   ('cold_os_cache', 'cold-os-large', 65536)):
            row = data.maybe(label, cohort, prof, 'read', size)
            cells.append('--' if row is None else f"{data.device_per_call(row)['dev']:.3f}")
        out.append(head + ' & ' + ' & '.join(cells) + r'\\')
    write('tab-nvme-media.tex', out + [r'\bottomrule\end{tabular}'])


