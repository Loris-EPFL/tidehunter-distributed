def read_cost_table():
    """Repeat pass at concurrency 1: every path reads memory except SPDK, which reads its SSD on every call."""
    heads = [('Native (local)', 'native'), ('Owner RPC, TCP', 'th_tcp'), ('Owner RPC, verbs', 'th_verbs'),
             ('NVMe-oF, kernel target', 'th_kernel'), ('NVMe-oF, SPDK target', 'th_spdk')]
    out = [r'\small', r'\begin{tabular}{lrrrrr}\toprule', r'Path, p50 / p99 \us & 64 B & 256 B & 1 KiB & 8 KiB & 64 KiB\\\midrule']
    for name, label in heads:
        cells = []
        for size in SIZES:
            row = data.pop(label, 'sealed_read', 'repeat_read-scalar-c1-baseline', 'read', size)
            cells.append(fmt(row['api_p50_us']) + '/' + fmt(row['api_p99_us']))
        out.append(name + ' & ' + ' & '.join(cells) + r'\\')
    write('tab-readcost.tex', out + [r'\bottomrule\end{tabular}'])


