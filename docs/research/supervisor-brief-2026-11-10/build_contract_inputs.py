#!/usr/bin/env python3
"""Build contract-separated tables from retained cloud CSVs. Launches nothing."""
import csv
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
WORKSPACE = HERE.parents[3]
RUNS = {
    'combined': WORKSPACE / 'checkpoint-work/combined-launch-20261113-firstput1/analysis/output',
    'run13': WORKSPACE / 'checkpoint-work/focused-launch-20261112-nvmeoffix4/analysis/output',
}
VALUES = []
SOURCES = {}


def rows(path):
    SOURCES[str(path)] = hashlib.sha256(path.read_bytes()).hexdigest()
    with path.open(newline='') as stream:
        return list(csv.DictReader(stream))


def one(records, **filters):
    selected = [r for r in records if all(r[k] == str(v) for k, v in filters.items())]
    assert len(selected) == 1, (filters, len(selected))
    return selected[0]


def number(label, row, column, path, fmt='.1f'):
    key = label + '-' + column
    entry = dict(label=key, value=row[column], source=str(path), column=column,
                 case_id=row.get('case_id', ''), operation=row.get('operation', ''))
    if entry not in VALUES:
        assert not any(r['label'] == key for r in VALUES), key
        VALUES.append(entry)
    return r'\N{B:contract-values:' + key + ':value|' + fmt + '}'


def table(name, headers, body, columns):
    text = [r'% Generated by build_contract_inputs.py; see contract-values.csv.',
            r'\small\setlength{\tabcolsep}{3pt}',
            r'\begin{tabular}{' + columns + r'}\toprule',
            ' & '.join(headers) + r'\\\midrule']
    text += [' & '.join(row) + r'\\' for row in body]
    text += [r'\bottomrule\end{tabular}']
    (HERE / name).write_text('\n'.join(text) + '\n')


def main():
    data = {(run, kind): rows(root / (kind + '.csv'))
            for run, root in RUNS.items() for kind in ('puts', 'reads')}
    comparison = rows(RUNS['combined'] / 'run13-comparison.csv')
    evidence_path = RUNS['combined'] / 'combined-kv-evidence.json'
    SOURCES[str(evidence_path)] = hashlib.sha256(evidence_path.read_bytes()).hexdigest()
    evidence = json.loads(evidence_path.read_text())
    for column in ('cases', 'measured_calls'):
        number('combined', evidence, column, evidence_path, ',.0f')
    run13_path = RUNS['run13'] / 'run13-evidence.json'
    SOURCES[str(run13_path)] = hashlib.sha256(run13_path.read_bytes()).hexdigest()
    run13 = json.loads(run13_path.read_text())
    assert run13['compared_cells'] == run13['status_counts']['completed']
    number('run13', run13, 'compared_cells', run13_path, ',.0f')

    # Only same-fleet, same-contract, unprofiled put pairs enter this table.
    body = []
    for run in RUNS:
        records = data[run, 'puts']
        for size, callers in ((1024, 1), (1024, 16), (65536, 1), (65536, 16)):
            for rep in (0, 1):
                shared = dict(value_size=size, concurrency=callers, repetition=rep,
                              contract='page_cache', diagnostic='not available')
                remote = [r for r in records if all(r[k] == str(v) for k, v in shared.items())
                          and r['backend'] == 'tidehunter_nvme_rdma'
                          and r['history_persistence'] == 'wal_replay'
                          and r['lease_ahead'] == 'True' and r['polled_writes'] == 'False']
                native = [r for r in records if all(r[k] == str(v) for k, v in shared.items())
                          and r['backend'] == 'native']
                if not remote or not native:
                    continue
                assert len(remote) == len(native) == 1
                path = RUNS[run] / 'puts.csv'
                left, right = remote[0], native[0]
                cells = [run, str(size // 1024), str(callers), str(rep)]
                for row in (left, right):
                    label = row['case_id']
                    cells.append('/'.join(number(label, row, field, path) for field in ('p50_us', 'p99_us', 'p999_us')))
                body.append(cells)
    table('tab-contract-a.tex', ['Run', 'KiB', '$c$', 'r', r'Leased A: p50/p99/p99.9 \us',
                               r'Native A: p50/p99/p99.9 \us'], body, 'lrrrll')

    sustained = one(data['combined', 'puts'], diagnostic='sustained')
    first = one(comparison, case_id='G20W-r0-8231343f2a568c3c567f')
    for field in ('p50_us', 'p99_us', 'p999_us', 'calls_per_second', 'mean_inflight_calls', 'calls_ge_5ms'):
        number('sustained', sustained, field, RUNS['combined'] / 'puts.csv', ',.0f' if field in ('calls_per_second', 'calls_ge_5ms') else '.1f')
    for field in ('first_call_us', 'run13_first_call_us'):
        number('first', first, field, RUNS['combined'] / 'run13-comparison.csv')

    # Separate class-B controls, never used as class-A put partners.
    body = []
    picks = [('puts', 'G19W-r0-c06459d77e52516b53ba', 'Leased put B'),
             ('puts', 'G19W-r0-4492454d4c36cacd3f74', 'Owner RPC put B'),
             ('reads', 'G19R-r0-f33d98a668f0ce648742', 'Live warm read (B setup)'),
             ('reads', 'G19R-r0-b36c3b48418ee8225b3a', 'Live warm, polled (B setup)'),
             ('reads', 'G19R-r0-2f756c11ec1013fce1e1', 'Live cold read (B setup)'),
             ('reads', 'G19R-r0-96d28dff2514d2bb19e6', 'Live cold read (B setup)'),
             ('reads', 'G19R-r0-f348d9f68461e8f6c8ed', 'Live cold read (B setup)'),
             ('reads', 'G19R-r0-c52fd3fdf7a4a94e2e67', 'Owner RPC cold (B setup)'),
             ('reads', 'G19R-r0-a4a0650e35a3dc6a6113', 'Owner RPC warm (B setup)'),
             ('reads', 'G19N-r0-bad6ac58440aa1315f0e', 'Native memory (B setup)')]
    for kind, case, name in picks:
        row = one(data['run13', kind], case_id=case)
        assert row['contract'] == 'durable'
        path = RUNS['run13'] / (kind + '.csv')
        body.append([name, str(int(row['value_size']) // 1024), row['concurrency'],
                     number(case, row, 'p50_us', path), number(case, row, 'p99_us', path),
                     number(case, row, 'p999_us', path)])
    table('tab-contract-b-controls.tex', ['Run 13 route / preparation', 'KiB', '$c$', r'p50 \us', r'p99 \us', r'p99.9 \us'], body, 'lrrrrr')

    # This is an explicit, non-ranking scale reference, not a matched comparison.
    historical = rows(HERE / 'populations.csv')
    body = []
    for operation in ('put', 'read'):
        for size in (1024, 65536):
            for callers in (1, 16):
                profile = 'point-mixed' if callers == 1 else ('write-concurrent' if operation == 'put' else 'read-concurrent')
                old = one(historical, label='valkey_rdma', cohort='primary_rf1', profile=profile,
                          operation=operation, value_bytes=size, outcome='success')
                new_cells = []
                if operation == 'put':
                    run = 'run13' if (size, callers) == (65536, 1) else 'combined'
                    records = [r for r in data[run, 'puts'] if r['backend'] == 'tidehunter_nvme_rdma'
                               and r['value_size'] == str(size) and r['concurrency'] == str(callers)
                               and r['diagnostic'] == 'not available' and r['contract'] == 'page_cache'
                               and r['history_persistence'] == 'wal_replay'
                               and r['lease_ahead'] == 'True' and r['polled_writes'] == 'False']
                    for row in sorted(records, key=lambda r: int(r['repetition'])):
                        new_cells.append(number(row['case_id'], row, 'p50_us', RUNS[run] / 'puts.csv'))
                    contract = 'A; ' + run
                else:
                    run = 'run13'
                    records = [r for r in data[run, 'reads'] if r['backend'] == 'tidehunter_nvme_rdma'
                               and r['value_size'] == str(size) and r['concurrency'] == str(callers)
                               and r['media_expected'] == 'cold']
                    for row in records:
                        new_cells.append(number(row['case_id'], row, 'p50_us', RUNS[run] / 'reads.csv'))
                    contract = 'B setup; cold; run13' if records else ''
                old_value = number('historical-' + old['case_id'] + '-' + operation, old,
                                   'api_p50_us', HERE / 'populations.csv')
                label = operation if operation == 'put' else 'read: from device'
                body.append([label, str(size // 1024), str(callers), '; '.join(new_cells) or 'not measured',
                             contract, old_value])
                if operation == 'read' and size == 1024 and callers == 1:
                    for backend, poll, label in (
                        ('tidehunter_nvme_rdma', '0', 'read live: from memory'),
                        ('tidehunter_nvme_rdma', '1', 'read live polled: from memory'),
                        ('tidehunter_verbs_native', 'not available', 'read owner RPC: from memory'),
                    ):
                        row = one(data['run13', 'reads'], backend=backend, poll_queues=poll,
                                  media_expected='memory', value_size=1024, concurrency=1)
                        assert row['contract'] == 'durable'
                        body.append([label, '1', '1',
                                     number(row['case_id'], row, 'p50_us', RUNS['run13'] / 'reads.csv'),
                                     'B setup; run13', old_value])
    table('tab-contract-indicative.tex', ['Call / TH path', 'KiB', '$c$', r'New TH p50 \us', 'TH contract / run', r'Historical Valkey B p50 \us'], body, 'lrrlll')

    with (HERE / 'contract-values.csv').open('w', newline='') as stream:
        writer = csv.DictWriter(stream, fieldnames=list(VALUES[0]))
        writer.writeheader()
        writer.writerows(VALUES)
    outputs = {name: hashlib.sha256((HERE / name).read_bytes()).hexdigest() for name in
               ('contract-values.csv', 'tab-contract-a.tex', 'tab-contract-b-controls.tex', 'tab-contract-indicative.tex')}
    (HERE / 'contract-inputs.json').write_text(json.dumps(dict(sources=SOURCES, outputs=outputs), indent=2) + '\n')
    print('Contract tables:', len(VALUES), 'source-linked numeric cells')


if __name__ == '__main__':
    main()
