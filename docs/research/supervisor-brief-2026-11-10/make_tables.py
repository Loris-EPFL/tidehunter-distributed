def appendix():
    groups = [
        ('Durable scalar puts', lambda r: r['shape'] == 'put' and r['durability'] in ('synchronous', 'value_wal_barrier')),
        ('Page-cache-acknowledged scalar puts', lambda r: r['shape'] == 'put' and r['durability'] in ('native', 'page_cache')),
        ('Batch writes and deletes', lambda r: r['shape'] in ('put_batch', 'delete')),
        ('Reads', lambda r: r['shape'] == 'read')]
    text = [r'\appendix']
    total = 0
    for heading, select in groups:
        selected = [(i, r) for i, r in enumerate(focused.ops) if select(r)]
        # Limit each page to 32 rows, with full headings repeated.
        for start in range(0, len(selected), 32):
            text += [r'\clearpage\section{' + heading + (' (continued)' if start else '') + '}',
                     r'Run 8, focused unified fleet. Each row is one CSV population, not pooled calls. '
                     r'API statistics are in \us. With two repetitions each cell is the median of per-repetition statistics. '
                     r'$n$ lists successful calls in each repetition; $r$ counts repetitions. '
                     r'B: native barrier; P: native page cache; S: owner synchronous; N: owner page cache. '
                     r'T: timeline; W: write profile; R: read profile; --: no profile. '
                     r'Row ids map to the zero-based row of \path{run8-ops_summary.csv}.',
                     r'\begin{center}\scriptsize\setlength{\tabcolsep}{3pt}',
                     r'\begin{tabular}{llrrrrrrrrr}\toprule',
                     r'Id/diag & Route/contract & KiB & $c$ & $n$ & $r$ & mean & p50 & p99 & p99.9 & State\\\midrule']
            for i, r in selected[start:start+32]:
                total += 1
                diag = json.loads(r['diagnostics'])
                d = 'T' if 'write_timeline_limit' in diag else 'W' if 'write_profile_limit' in diag else 'R' if diag else '--'
                contract = {'value_wal_barrier': 'B', 'page_cache': 'P', 'synchronous': 'S', 'native': 'N'}[r['durability']]
                route = {'owner verbs': 'verbs', 'owner TCP': 'TCP', 'verbs mTLS': 'mTLS',
                         'native': 'native', 'hybrid kernel DIRECT': 'kernel D',
                         'hybrid kernel buffered': 'kernel B', 'hybrid SPDK': 'SPDK'}[r['route']]
                state = r['cache_state'] if r['shape'] == 'read' else r['shape'].replace('put_batch', 'batch')
                if r['key_policy'] == 'new':
                    state += '/new'
                cells = [f'{i:03d}/{d}', route + '/' + contract, str(int(r['size_bytes']) // 1024),
                         r['concurrency'], number(f'D:op{i:03d}:n'), r['repetition_count']] + [
                         number(f'D:op{i:03d}:{col}') for col in ['mean_us', 'p50_us', 'p99_us', 'p999_us']] + [state]
