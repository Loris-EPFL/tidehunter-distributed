def write_numbers():
    keys = set()
    pattern = re.compile(r'\\(%s)\{([^{}]+)\}\{([^{}]+)\}\{([^{}]+)\}' % '|'.join(MACROS))
    for path in sorted(HERE.glob('*.tex')):
        if path.name in ('numbers.tex', 'macros.tex'):
            continue
        text = path.read_text()
        keys.update(re.findall(r'\\N\{([^{}]+)\}', text))
        for name, kind, label, size in pattern.findall(text):
            keys.add(f'{kind}:{label}:{MACROS[name]}:{size}')
    lines = ['% Generated from audited CSV inputs. Do not edit.']
    baseline = json.loads((HERE / 'number-baseline.json').read_text())
    keys.update(baseline)
    for key in sorted(keys):
        lines.append('\\expandafter\\gdef\\csname n@\\detokenize{%s}\\endcsname{%s}' %
                     (key, evaluate(key, data, stats)))
    write('numbers.tex', lines)
