def number(key):
    return r'\N{' + key + '}'


def table(name, headers, rows):
    out = [r'\small\setlength{\tabcolsep}{4pt}',
           r'\begin{tabular}{l' + 'r' * (len(headers) - 1) + r'}\toprule',
           ' & '.join(headers) + r'\\\midrule']
    out += [' & '.join(row) + r'\\' for row in rows]
    write(name, out + [r'\bottomrule\end{tabular}'])


def decomposition(name, series):
    tokens = list(COMPONENTS)
    names = {'persist': 'Owner append-persist (includes software)',
             'network': 'Network (stacks, TLS, dispatch included)',
             'coordinator': 'Coordinator / native library insert$^{a}$',
             'owner': 'Owner software', 'durable': 'Durable wait / native file sync$^{a}$',
             'coalescing': 'Waiting and coalescing', 'queue': 'Client queueing and wake-up',
             'residual': 'Residual', 'messaging': 'Client encode, decode, verify',
             'device': 'SSD device', 'combined': 'Device + fabric + stack (unsplit)',
             'exchange': 'Owner + network exchange (unsplit)'}
    rows = [[names[t]] + [number(f'C:{s}:{t}') for s in series] for t in tokens]
    rows += [[r'\textbf{TOTAL: same-case API mean}'] +
             [number(f'D:{s}:mean_us') for s in series],
             ['API p50'] + [number(f'D:{s}:p50_us') for s in series]]
    table(name, ['Component, mean ' + r'\us'] +
          [SHORT[focused.series[s]['route']] for s in series], rows)


